"""Validate the actual GUI and capture screenshots using generated demo data.

Requires Playwright + Chromium in addition to the app runtime. Run generate_demo.py
without --runtime-root first. Only synthetic datasets are accepted by this script.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import socket
import subprocess
import time
import urllib.request

from playwright.sync_api import sync_playwright


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, required=True)
    parser.add_argument("--state", type=Path, required=True, help="New, isolated demo state directory")
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1]/"docs/screenshots")
    args = parser.parse_args()
    data, state, output = args.data.resolve(), args.state.resolve(), args.output.resolve()
    if not (data/"SYNTHETIC.txt").is_file():
        parser.error("Only datasets generated by generate_demo.py are accepted")
    if state.exists():
        parser.error("Use a new state directory so demo checks cannot change existing annotations")
    output.mkdir(parents=True, exist_ok=True)
    with socket.socket() as sock:
        sock.bind(("127.0.0.1",0)); port = sock.getsockname()[1]
    script_dir = Path(__file__).resolve().parent
    env = {**os.environ, "HISTOLOOP_DATA_ROOT":str(data), "HISTOLOOP_STATE_DIR":str(state),
           "HISTOLOOP_ORIGINAL_MANIFEST":str(data/"case_split.xlsx"), "HISTOLOOP_PORT":str(port),
           "HISTOLOOP_CACHE_DIR":str(state.parent/(state.name+"-cache")), "HISTOLOOP_ENABLE_COMPUTE":"0"}
    errors, failed_requests = [], []
    with (output.parent/"screenshot-server.log").open("w") as log:
        process = subprocess.Popen(["bash",str(script_dir/"run_native.sh")], env=env, stdout=log, stderr=log)
        try:
            base = f"http://127.0.0.1:{port}"
            deadline = time.monotonic()+60
            while time.monotonic() < deadline:
                if process.poll() is not None:
                    raise RuntimeError("Native startup failed; inspect screenshot-server.log")
                try:
                    urllib.request.urlopen(base+"/health", timeout=1); break
                except OSError:
                    time.sleep(.1)
            else:
                raise RuntimeError("Server startup timed out")
            token = (state/"access_token").read_text().strip()
            with sync_playwright() as manager:
                browser = manager.chromium.launch(headless=True, args=["--no-sandbox"])
                page = browser.new_page(viewport={"width":1600,"height":1000}, device_scale_factor=1)
                page.on("pageerror", lambda error: errors.append(str(error)))
                page.on("response", lambda response: failed_requests.append({"path":response.url.split("?")[0].replace(base,""),"status":response.status}) if response.status>=400 else None)
                started = time.monotonic()
                page.goto(base+"/?token="+token)
                page.wait_for_function("S.detail && !S.loading && S.viewer.world.getItemCount()>0")
                page.wait_for_function("S.viewer.world.getItemAt(0).getFullyLoaded()")
                page.locator("#reviewer").fill("Demo reviewer")
                page.locator("#showAll").click()
                page.wait_for_timeout(500)
                assert page.title().startswith("HistoLoop")
                assert page.locator("#trainButton").is_disabled()
                initial_seconds = round(time.monotonic()-started,3)
                page.screenshot(path=str(output/"main-interface.png"))
                page.locator("#histogram").scroll_into_view_if_needed()
                page.screenshot(path=str(output/"score-distribution.png"))
                page.locator('[data-label="0"]').scroll_into_view_if_needed()
                page.locator("#datasetSelect").select_option("validation")
                page.wait_for_function("S.dataset==='validation' && S.detail?.dataset_id==='validation' && !S.loading")
                page.locator("#splitSelect").select_option("new")
                page.wait_for_function("S.filtered.length===1")
                page.locator(".slide-open").first.click()
                page.wait_for_function("S.detail?.name==='DEMO_02_02' && !S.loading")
                page.wait_for_timeout(400)
                page.screenshot(path=str(output/"dataset-selection.png"))
                page.locator("#splitSelect").select_option("all")
                page.evaluate("focusRegion([[400,400],[1400,400],[1400,1400],[400,1400]])")
                page.wait_for_timeout(700)
                page.screenshot(path=str(output/"wsi-viewer.png"))
                page.locator('[data-label="1"]').click()
                page.locator('[data-tool="rectangle"]').click()
                page.locator("#regionNote").fill("Synthetic demonstration correction")
                revision = page.evaluate("S.detail.revision")
                points = page.evaluate("""()=>{const r=$('viewerWrap').getBoundingClientRect();const item=S.viewer.world.getItemAt(0);
                    return [[650,650],[1150,1150]].map(p=>{const q=item.imageToViewerElementCoordinates(new OpenSeadragon.Point(...p));return [r.left+q.x,r.top+q.y];});}""")
                page.mouse.move(*points[0]); page.mouse.down(); page.mouse.move(*points[1],steps=15); page.mouse.up()
                page.wait_for_function("revision=>S.detail.revision>revision&&!S.saving", arg=revision)
                manual = page.evaluate("S.detail.manual_tiles")
                saved_slide = page.evaluate("S.detail.id")
                assert manual > 0
                page.wait_for_timeout(400)
                page.screenshot(path=str(output/"annotation-editor.png"))
                page.locator('[data-tab="history"]').click()
                page.wait_for_function("S.history.some(event=>event.action==='label')")
                page.screenshot(path=str(output/"annotation-history.png"))
                page.reload(); page.wait_for_function("S.detail && !S.loading")
                # Preferences belong to the server login; the screenshot reviewer
                # is a synthetic audit actor. Reopen the corrected slide explicitly.
                page.evaluate("id=>loadSlide(id)", saved_slide)
                page.wait_for_function("id=>S.detail?.id===id&&!S.loading", arg=saved_slide)
                assert page.evaluate("S.detail.manual_tiles") == manual
                for width in (1024,768,390):
                    page.set_viewport_size({"width":width,"height":850}); page.wait_for_timeout(150)
                    assert page.evaluate("document.documentElement.scrollWidth<=innerWidth")
                assert not errors, errors
                assert not failed_requests, failed_requests
                report = {"synthetic_data":True,"passed":True,"initial_load_seconds":initial_seconds,
                          "manual_tiles":manual,"page_errors":errors,"failed_requests":failed_requests,
                          "checks":["native startup","HistoLoop branding","CPU compute controls",
                                    "dataset switching","split filtering","sample navigation","WSI tile loading",
                                    "prediction overlay","rectangle autosave","history","reload persistence","responsive layout"]}
                (output.parent/"screenshot-validation.json").write_text(json.dumps(report,indent=2)+"\n")
                print(json.dumps(report,indent=2))
                browser.close()
        finally:
            process.terminate()
            try:
                process.wait(timeout=15)
            except subprocess.TimeoutExpired:
                process.kill(); process.wait()


if __name__ == "__main__":
    main()
